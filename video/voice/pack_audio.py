"""Bundle the narration clips into narration.js so explainer.html can play them from a local file.

Reads audio/lines.tsv (scene id <TAB> line) and, for each scene, audio/<id>.voice.m4a (the final voice, from
assemble_voice.py), .mp3, .m4a (the scratch voice) or .wav, first found, plus each clip's
chunk start times (audio/timings-voice.json for the final voice, audio/timings-scratch.json otherwise),
which the page uses to keep every visual beat on its line.
Run after changing any clip (from the repo root):  python video/voice/pack_audio.py video/<video>
"""
import base64
import json
import pathlib
import re
import sys

from make_scratch import VIDEO

AUDIO = VIDEO / "audio"
MIME = {".voice.m4a": "audio/mp4", ".mp3": "audio/mpeg", ".m4a": "audio/mp4", ".wav": "audio/wav"}

def load(name):
    f = AUDIO / name
    return json.loads(f.read_text()) if f.exists() else {}


TIMES = {".voice.m4a": load("timings-voice.json"), ".mp3": load("timings-elevenlabs.json"), ".m4a": load("timings-scratch.json"), ".wav": load("timings-scratch.json")}
out = {}
for row in (AUDIO / "lines.tsv").read_text(encoding="utf-8").splitlines():
    if not row.strip():
        continue
    sid, text = row.split("\t", 1)
    clean = re.sub(r"\s+", " ", re.sub(r"\s*\[\[[^\]]*\]\]\s*|\s*\|\s*", " ", text)).strip()   # drop pause tags and chunk marks
    entry = {"text": clean}
    for ext in (".voice.m4a", ".mp3", ".m4a", ".wav"):
        f = AUDIO / f"{sid}{ext}"
        if f.exists():
            entry.update(mime=MIME[ext], file=f.name, b64=base64.b64encode(f.read_bytes()).decode())
            tm = TIMES[ext].get(sid)
            if tm:
                entry.update(cues=tm["cues"], hold=tm.get("hold", 0))
            break
    out[sid] = entry
    print(f"{sid:12s} {entry.get('file', '(no audio: text only)')}")

js = "// GENERATED by pack_audio.py - do not edit by hand.\nwindow.NARR = " + json.dumps(out) + ";\n"
(VIDEO / "narration.js").write_text(js, encoding="utf-8")
print(f"wrote narration.js ({len(js) / 1e6:.1f} MB)")
