"""Build the chart decision tree from tokens/chooser.json (the single source).

    python tools/build_chooser.py        (tokens/build.py runs it too)

Checks the tree (every cookbook page exists, every condition is defined and implemented in mckviz.chooser, every
color pattern is defined), copies it into the package (python/mckviz/_chooser.json, which mv.suggest reads and the
Copilot skill ships), and writes docs/chart-decision-tree.md, which the agent skill carries as a reference. The guide's
chooser spread is to be generated from the same file.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tokens" / "chooser.json"
PKG = ROOT / "python" / "mckviz" / "_chooser.json"
DOC = ROOT / "docs" / "chart-decision-tree.md"


def check(tree: dict) -> list[str]:
    problems = []
    implemented = set(re.findall(r'fact\("([a-z_]+)"', (ROOT / "python" / "mckviz" / "chooser.py").read_text(
        encoding="utf-8")))
    trig, colors = tree["triggers"], tree["colors"]
    for key in trig:
        if key not in implemented:
            problems.append(f"condition {key!r} has no fact() in python/mckviz/chooser.py")
    for s in tree["shapes"]:
        for q in s["questions"]:
            leaves = [q["start"], *q["further"]]
            for leaf in leaves:
                if not (ROOT / "docs" / "cookbook" / f"{leaf['page']}.md").exists():
                    problems.append(f"{s['id']}: no cookbook page {leaf['page']!r}")
            for f in q["further"]:
                if f["when"] not in trig:
                    problems.append(f"{s['id']}: undefined condition {f['when']!r}")
            if q.get("needs") and q["needs"] not in trig:
                problems.append(f"{s['id']}: undefined condition {q['needs']!r}")
            for c in [q["color"], *(sw["use"] for sw in q.get("color_switch", []))]:
                if c not in colors:
                    problems.append(f"{s['id']}: undefined color pattern {c!r}")
    return problems


def markdown(tree: dict) -> str:
    trig, colors = tree["triggers"], tree["colors"]
    out = ["<!-- GENERATED by tools/build_chooser.py from tokens/chooser.json. Edit that file, not this one. -->",
           "# Chart decision tree", "",
           "Choose a chart in three steps, in this order. The tree starts from **what is in the data**, because that "
           "can be read from the columns, then asks **what the reader should see**, then gives a chart to **start "
           "with** and the conditions under which to **go further** to a richer form. Color comes last, from what it "
           "has to encode. [choosing-a-chart.md](choosing-a-chart.md) is the same advice by question type, and the "
           "cookbook page of each chart has its spec and code.", "",
           "In Python, `mv.suggest(df)` reads the table, places it in this tree, checks every condition against the "
           "data and prints the result. Check how it read the columns, and pass `category=`, `measure=`, `size=` or "
           "`time=` when a guess is wrong.", "",
           "**Start with** is right when no condition holds: it is the chart most readers decode fastest. When a "
           "condition holds, the richer chart usually says more; use it when it answers the question better, and say "
           "which condition you used in the chart brief:", "",
           "```", "Path:   <shape> -> <question type> -> <chart> (start, or go further: <condition>)",
           "Color:  <pattern> (<why>)", "```", "",
           "## 1. What is in the data?", "", "| Shape | Looks like |", "|---|---|"]
    for s in tree["shapes"]:
        out.append(f"| [{s['label']}](#{s['id'].replace('_', '-')}) | {s['looks_like']} |")
    out += ["", "## 2–3. What should the reader see, and which chart?", ""]
    for s in tree["shapes"]:
        out += [f'<a id="{s["id"].replace("_", "-")}"></a>', f"### {s['label']}", "", s["looks_like"], ""]
        for q in s["questions"]:
            needs = f" *(when there is {trig[q['needs']]})*" if q.get("needs") else ""
            st = q["start"]
            helper = f" (`{st['helper']}`)" if st.get("helper") else ""
            out += [f"**{q['ask']}** ({q['type']}){needs}", "",
                    f"- **Start with:** [{st['chart']}](cookbook/{st['page']}.md){helper}"]
            for f in q["further"]:
                h = f" (`{f['helper']}`)" if f.get("helper") else ""
                why = f": {f['why']}" if f.get("why") else ""
                out.append(f"- **Go further** when {trig[f['when']]}: [{f['chart']}](cookbook/{f['page']}.md){h}{why}")
            out.append(f"- **Avoid:** {q['avoid']}")
            col = f"- **Color:** {colors[q['color']]['name']}"
            for sw in q.get("color_switch", []):
                col += f"; {colors[sw['use']]['name']} when {trig.get(sw['when'], sw['when'])}"
            out += [col, ""]
    out += ["## 4. What does color encode?", "",
            "Grey first, then color only the point. Pick the pattern from what the color has to say:", "",
            "| Pattern | Use when | In mckviz |", "|---|---|---|"]
    for c in colors.values():
        out.append(f"| **{c['name']}** | {c['when']} | `{c['how']}` |")
    out += ["", "The hex values of every role are in [rules.md](rules.md); [color.md](color.md) has the reasoning.", ""]
    return "\n".join(out)


def build() -> None:
    tree = json.loads(SRC.read_text(encoding="utf-8"))
    problems = check(tree)
    if problems:
        sys.exit("chart decision tree:\n  " + "\n  ".join(problems))
    shutil.copyfile(SRC, PKG)
    DOC.write_text(markdown(tree), encoding="utf-8", newline="\n")
    print(f"  wrote docs/chart-decision-tree.md and python/mckviz/_chooser.json ({len(tree['shapes'])} shapes)")


if __name__ == "__main__":
    build()
